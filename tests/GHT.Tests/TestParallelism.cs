using Xunit;

// 计时类用例（首批窗口、预算取消、竞态重试）依赖「定时器到点就能立刻执行续体」。
//
// CI 的 Windows 运行器只有 2 个 vCPU，xunit 默认按核数并行，于是这些用例会和
// CPU 密集的用例（例如 SweepRaceTests 里反复换池的那条）抢同一个线程池：
// 同一份提交，两次运行量到的首批时间分别是 1524ms（窗口 200ms）与 4726ms（窗口 150ms），
// 而 build 那次是绿的 —— 失败的是运行器调度，不是被测逻辑。
//
// 把这个噪声从「断言阈值」里挤出去，只能靠不并行：串行后每条用例的续体都不再排队，
// 计时才有意义。代价是整套用例多跑几秒，比「随机挂一条、每次都要重新判断是不是回归」便宜得多。
[assembly: CollectionBehavior(DisableTestParallelization = true)]
